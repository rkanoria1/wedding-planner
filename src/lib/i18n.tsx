const DICTS: Record<Lang, Record<string, string>> = { en: {}, hi: HI };

interface LangValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Translate a key; `fallback` (or the key) when untranslated. Optional `{n}` vars. */
  t: (key: string, fallback?: string, vars?: Record<string, string | number>) => string;
}

const LangContext = createContext<LangValue | null>(null);
const STORAGE_KEY = "appLang";

function applyVars(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    s
  );
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "hi" || saved === "en") setLangState(saved);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
    document.documentElement.lang = l;
  }, []);

  const t = useCallback(
    (key: string, fallback?: string, vars?: Record<string, string | number>) =>
      applyVars(DICTS[lang][key] ?? fallback ?? key, vars),
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): LangValue {
  const ctx = useContext(LangContext);
  if (!ctx) {
    return {
      lang: "en",
      setLang: () => {},
      t: (k, f, vars) => applyVars(f ?? k, vars),
    };
  }
  return ctx;
}

/** Translate a booking category label when a key exists. */
export function catKey(label: string) {
  return `bcat.${label}`;
}
